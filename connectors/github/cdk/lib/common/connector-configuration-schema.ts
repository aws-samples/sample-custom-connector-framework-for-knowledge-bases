import { readFileSync } from "node:fs";
import { Ajv2020, ErrorObject, ValidateFunction } from "ajv/dist/2020";
import { ConfigurationError, isJsonObject } from "custom-connector-framework-cdk";

/** A part of the generated schema, by its JSON pointer. */
export enum SchemaPart {
  CONFIGURATION = "",
  OWNER = "/properties/owner",
  REPOSITORY_NAME = "/properties/repositories/items",
}

export interface SchemaCheckRequest {
  readonly part: SchemaPart;
  readonly value: unknown;
  /** The configuration key the value came from, which every error names first. */
  readonly field: string;
}

const SCHEMA_ID = "https://ccf.local/github-connector-configuration.schema.json";

/** The key an error names: the field, the instance path's segments, and a missing or extra property. */
const errorKey = ({
  field,
  error,
}: {
  readonly field: string;
  readonly error: ErrorObject;
}): string => {
  const segments = error.instancePath.split("/").filter((segment) => segment.length > 0);
  const { params } = error;
  const property = [params.missingProperty, params.additionalProperty].find(
    (value): value is string => typeof value === "string",
  );
  return [field, ...segments, ...(property === undefined ? [] : [property])].join(".");
};

/**
 * The backend's `GitHubConnectorConfiguration` as JSON Schema, generated by `make build` into
 * `backend/generated/`, so the CDK checks a connector configuration with the model's own rules.
 */
export class ConnectorConfigurationSchema {
  private constructor(private readonly validators: ReadonlyMap<SchemaPart, ValidateFunction>) {}

  public static fromFile(path: string): ConnectorConfigurationSchema {
    const schema: unknown = JSON.parse(readFileSync(path, "utf8"));
    if (!isJsonObject(schema)) throw new ConfigurationError(`${path} isn't a JSON Schema object.`);
    const ajv = new Ajv2020({ allErrors: false, strict: false });
    ajv.addSchema({ ...schema, $id: SCHEMA_ID });
    return new ConnectorConfigurationSchema(
      new Map(
        Object.values(SchemaPart).map((part) => [
          part,
          ajv.compile({ $ref: `${SCHEMA_ID}#${part}` }),
        ]),
      ),
    );
  }

  /** Throws `ConfigurationError`: `"<field>.<path>" <rule>.` for the first rule the value breaks. */
  public check({ part, value, field }: SchemaCheckRequest): void {
    const validate = this.validators.get(part);
    if (validate === undefined) throw new Error(`No validator for the schema part "${part}".`);
    if (validate(value)) return;
    const error = validate.errors?.at(0);
    if (error === undefined) throw new ConfigurationError(`"${field}" breaks the schema.`);
    throw new ConfigurationError(
      `"${errorKey({ field, error })}" ${error.message ?? "is invalid"}.`,
    );
  }
}
